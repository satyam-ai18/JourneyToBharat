/**
 * Reliable lookup function for a destination ID.
 * Returns the verified image URL and metadata.
 * If not found, returns null so a neutral, branded placeholder is used rather than any unrelated image!
 */
export function getVerifiedDestinationImage(destinationId, fallbackName = "Sacred Temple") {
  if (!destinationId) return createTemplePlaceholder(fallbackName);
  const match = VERIFIED_IMAGE_REGISTRY[destinationId];
  if (match && match.url) return match.url;
  return createTemplePlaceholder(fallbackName);
}
